import { ID, Permission, Query, Role } from "appwrite";
import * as DocumentPicker from "expo-document-picker";
import * as FileSystem from "expo-file-system";
import * as Sharing from "expo-sharing";
import { Linking, Platform } from "react-native";
import { storage, tablesDB } from "@/constants/appwrite";
import { MAX_FILE_BYTES, VAULT } from "@/constants/vault";
import type { VaultFileRow, VaultGroup } from "@/types/vault";
import { base64ToBytes, bytesToBase64 } from "./binary";
import {
  formatBytes,
  isAllowedFileName,
  kindOf,
  mimeTypeFor,
  sanitizeFileName,
} from "./format";

/**
 * Bytes live in the bucket; a row carries the metadata, so a group can be
 * listed and searched without touching storage.
 *
 * Access model: every file is created with read/update/delete granted to the
 * owning team (and to the uploader). Appwrite enforces that server-side — the
 * UI never decides who may see what.
 */

export interface PickedAsset {
  uri: string;
  name: string;
  size?: number;
  mimeType?: string;
  /** Present on web, where the picker hands back a real File. */
  file?: File;
  /** Present when we're uploading generated bytes (an edit) rather than a pick. */
  bytes?: Uint8Array;
}

function filePermissions(teamId: string, uploaderId: string): string[] {
  return [
    Permission.read(Role.team(teamId)),
    Permission.update(Role.team(teamId)),
    Permission.delete(Role.team(teamId)),
    Permission.read(Role.user(uploaderId)),
    Permission.update(Role.user(uploaderId)),
    Permission.delete(Role.user(uploaderId)),
  ];
}

function asFileRow(row: unknown): VaultFileRow {
  return row as VaultFileRow;
}

/** Ask the OS for files. Returns [] when the user cancels. */
export async function pickVaultFiles(
  options: { imagesOnly?: boolean } = {},
): Promise<PickedAsset[]> {
  const result = await DocumentPicker.getDocumentAsync({
    multiple: true,
    copyToCacheDirectory: true,
    type: options.imagesOnly
      ? ["image/*"]
      : [
          "application/pdf",
          "image/*",
          "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
          "application/vnd.ms-excel",
          "text/csv",
          "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
          "application/msword",
          "application/vnd.openxmlformats-officedocument.presentationml.presentation",
          "text/plain",
        ],
  });
  if (result.canceled) return [];
  return result.assets.map((asset) => ({
    uri: asset.uri,
    name: asset.name ?? "file",
    size: asset.size,
    mimeType: asset.mimeType,
    file: asset.file,
  }));
}

/**
 * Turn an asset (or freshly generated bytes) into the `File` object the
 * Appwrite SDK accepts.
 *
 * On web the picker already gives us a real File. On native we wrap a Blob in
 * React Native's global `File` — the SDK's upload path checks
 * `value instanceof File` and slices it for chunked uploads, so a plain Blob
 * is not enough.
 */
async function toUploadableFile(params: {
  uri?: string;
  file?: File;
  bytes?: Uint8Array;
  name: string;
  mimeType: string;
}): Promise<File> {
  if (params.file) return params.file;

  if (Platform.OS === "web") {
    if (!params.bytes) throw new Error("Nothing to upload.");
    return new File([params.bytes as unknown as BlobPart], params.name, {
      type: params.mimeType,
    });
  }

  let uri = params.uri;
  if (!uri && params.bytes) {
    // Native uploaders need a real file on disk, so stage the bytes in cache.
    const staged = `${FileSystem.cacheDirectory}${Date.now()}-${params.name}`;
    await FileSystem.writeAsStringAsync(staged, bytesToBase64(params.bytes), {
      encoding: FileSystem.EncodingType.Base64,
    });
    uri = staged;
  }
  if (!uri) throw new Error("Nothing to upload.");

  const response = await fetch(uri);
  const blob = await response.blob();
  return new File([blob], params.name, { type: params.mimeType });
}

interface ValidatedUpload {
  name: string;
  mimeType: string;
  file: File;
}

async function prepareUpload(asset: PickedAsset): Promise<ValidatedUpload> {
  const name = sanitizeFileName(asset.name);

  if (!isAllowedFileName(name)) {
    throw new Error(
      `“${name}” isn't a supported file type. Documents, spreadsheets, ` +
        `presentations, PDFs and images are allowed.`,
    );
  }

  const reportedSize = asset.size ?? asset.bytes?.length;
  if (typeof reportedSize === "number" && reportedSize > MAX_FILE_BYTES) {
    throw new Error(
      `“${name}” is ${formatBytes(reportedSize)} — the limit is ` +
        `${formatBytes(MAX_FILE_BYTES)}.`,
    );
  }

  const mimeType = mimeTypeFor(name, asset.mimeType);
  const file = await toUploadableFile({
    uri: asset.uri || undefined,
    file: asset.file,
    bytes: asset.bytes,
    name,
    mimeType,
  });

  if (file.size > MAX_FILE_BYTES) {
    throw new Error(
      `“${name}” is ${formatBytes(file.size)} — the limit is ` +
        `${formatBytes(MAX_FILE_BYTES)}.`,
    );
  }

  return { name, mimeType, file };
}

/** Upload bytes to the bucket with team-scoped permissions. */
async function createStorageFile(params: {
  group: VaultGroup;
  upload: ValidatedUpload;
  userId: string;
  onProgress?: (percent: number) => void;
}) {
  return storage.createFile({
    bucketId: VAULT.bucketId,
    fileId: ID.unique(),
    file: params.upload.file,
    permissions: filePermissions(params.group.teamId, params.userId),
    onProgress: (progress) => params.onProgress?.(progress.progress ?? 0),
  });
}

async function createFileRow(params: {
  group: VaultGroup;
  upload: ValidatedUpload;
  bucketFileId: string;
  size: number;
  userId: string;
  userName: string;
}): Promise<VaultFileRow> {
  const row = await tablesDB.createRow({
    databaseId: VAULT.databaseId,
    tableId: VAULT.filesTableId,
    rowId: ID.unique(),
    data: {
      groupId: params.group.$id,
      name: params.upload.name,
      bucketFileId: params.bucketFileId,
      size: params.size,
      mimeType: params.upload.mimeType,
      kind: kindOf(params.upload.mimeType, params.upload.name),
      uploadedBy: params.userId,
      uploadedByName: params.userName,
    },
    permissions: filePermissions(params.group.teamId, params.userId),
  });
  return asFileRow(row);
}

/** Upload one picked asset into a group. */
export async function uploadVaultFile(params: {
  group: VaultGroup;
  asset: PickedAsset;
  userId: string;
  userName: string;
  onProgress?: (percent: number) => void;
}): Promise<VaultFileRow> {
  const upload = await prepareUpload(params.asset);
  const bucketFile = await createStorageFile({
    group: params.group,
    upload,
    userId: params.userId,
    onProgress: params.onProgress,
  });

  try {
    return await createFileRow({
      group: params.group,
      upload,
      bucketFileId: bucketFile.$id,
      size: bucketFile.sizeOriginal ?? upload.file.size,
      userId: params.userId,
      userName: params.userName,
    });
  } catch (error) {
    // Never leave bytes behind without a row pointing at them.
    await storage
      .deleteFile({ bucketId: VAULT.bucketId, fileId: bucketFile.$id })
      .catch(() => {});
    throw error;
  }
}

/** Upload generated bytes — an edited photo, a re-saved PDF. */
export async function uploadVaultBytes(params: {
  group: VaultGroup;
  bytes: Uint8Array;
  name: string;
  mimeType: string;
  userId: string;
  userName: string;
}): Promise<VaultFileRow> {
  return uploadVaultFile({
    group: params.group,
    userId: params.userId,
    userName: params.userName,
    asset: {
      uri: "",
      name: params.name,
      size: params.bytes.length,
      mimeType: params.mimeType,
      bytes: params.bytes,
    },
  });
}

/** Replace a file's contents, keeping its row (and therefore its identity). */
export async function replaceVaultFileBytes(params: {
  group: VaultGroup;
  row: VaultFileRow;
  bytes: Uint8Array;
  mimeType: string;
  userId: string;
}): Promise<VaultFileRow> {
  const upload = await prepareUpload({
    uri: "",
    name: params.row.name,
    size: params.bytes.length,
    mimeType: params.mimeType,
    bytes: params.bytes,
  });

  const bucketFile = await createStorageFile({
    group: params.group,
    upload,
    userId: params.userId,
  });

  const previousBucketFileId = params.row.bucketFileId;

  await tablesDB.updateRow({
    databaseId: VAULT.databaseId,
    tableId: VAULT.filesTableId,
    rowId: params.row.$id,
    data: {
      bucketFileId: bucketFile.$id,
      size: params.bytes.length,
      mimeType: params.mimeType,
      kind: kindOf(params.mimeType, params.row.name),
    },
  });

  // Only bin the old bytes once the row points at the new ones.
  await storage
    .deleteFile({ bucketId: VAULT.bucketId, fileId: previousBucketFileId })
    .catch(() => {});

  return {
    ...params.row,
    bucketFileId: bucketFile.$id,
    size: params.bytes.length,
    mimeType: params.mimeType,
  };
}

/** Files in a group, newest first. Team permission decides what comes back. */
export async function listGroupFiles(groupId: string): Promise<VaultFileRow[]> {
  const result = await tablesDB.listRows({
    databaseId: VAULT.databaseId,
    tableId: VAULT.filesTableId,
    queries: [
      Query.equal("groupId", groupId),
      Query.orderDesc("$createdAt"),
      Query.limit(200),
    ],
  });
  return (result.rows ?? []).map(asFileRow);
}

export async function getVaultFile(rowId: string): Promise<VaultFileRow> {
  return asFileRow(
    await tablesDB.getRow({
      databaseId: VAULT.databaseId,
      tableId: VAULT.filesTableId,
      rowId,
    }),
  );
}

/** Delete both the bytes and the row. */
export async function deleteVaultFile(row: VaultFileRow): Promise<void> {
  await deleteStorageFile(row.bucketFileId).catch(() => {});
  await deleteVaultFileRow(row.$id);
}

export async function deleteStorageFile(bucketFileId: string): Promise<void> {
  await storage.deleteFile({ bucketId: VAULT.bucketId, fileId: bucketFileId });
}

export async function deleteVaultFileRow(rowId: string): Promise<void> {
  await tablesDB.deleteRow({
    databaseId: VAULT.databaseId,
    tableId: VAULT.filesTableId,
    rowId,
  });
}

/** URL that renders inline (images, PDF previews). */
export function viewUrlFor(row: VaultFileRow): string {
  return String(
    storage.getFileView({ bucketId: VAULT.bucketId, fileId: row.bucketFileId }),
  );
}

/** URL that forces a download. */
export function downloadUrlFor(row: VaultFileRow): string {
  return String(
    storage.getFileDownload({ bucketId: VAULT.bucketId, fileId: row.bucketFileId }),
  );
}

/**
 * Appwrite renders image previews server-side (resize, quality, format) —
 * far cheaper than pulling a 12 MP photo to show a thumbnail. Null for
 * anything that isn't an image, or if the bucket has transformations off.
 */
export function thumbnailUrlFor(
  row: VaultFileRow,
  options: { width?: number; height?: number; quality?: number } = {},
): string | null {
  if (row.kind !== "image") return null;
  try {
    return String(
      storage.getFilePreview({
        bucketId: VAULT.bucketId,
        fileId: row.bucketFileId,
        width: options.width ?? 400,
        height: options.height ?? 400,
        quality: options.quality ?? 60,
      }),
    );
  } catch {
    return null;
  }
}

/**
 * Hand a file to the user's device.
 *
 * Web: the browser downloads it (the session cookie rides along).
 * Native: fetch into the cache, then open the share sheet so it can be saved
 * or handed to an app that understands the type.
 */
export async function downloadVaultFile(
  row: VaultFileRow,
): Promise<"downloaded" | "shared"> {
  const url = downloadUrlFor(row);

  if (Platform.OS === "web") {
    await Linking.openURL(url);
    return "downloaded";
  }

  const target = `${FileSystem.cacheDirectory}${sanitizeFileName(row.name)}`;
  const existing = await FileSystem.getInfoAsync(target);
  if (existing.exists) await FileSystem.deleteAsync(target, { idempotent: true });

  const result = await FileSystem.downloadAsync(url, target);
  if (result.status !== 200) {
    throw new Error(
      `Download failed (HTTP ${result.status}). A 401 here means the file ` +
        `belongs to a group you're no longer a member of.`,
    );
  }

  if (await Sharing.isAvailableAsync()) {
    await Sharing.shareAsync(result.uri, {
      mimeType: row.mimeType,
      dialogTitle: row.name,
    });
    return "shared";
  }
  return "downloaded";
}

/**
 * Read a stored file into memory.
 *
 * On web the session lives in a cookie, so the request has to be made with
 * `credentials: 'include'` — otherwise private files come back as 401.
 */
export async function readVaultBytes(row: VaultFileRow): Promise<Uint8Array> {
  const url = viewUrlFor(row);

  if (Platform.OS === "web") {
    const response = await fetch(url, { credentials: "include" });
    if (!response.ok) {
      throw new Error(`Could not read the file (HTTP ${response.status}).`);
    }
    return new Uint8Array(await response.arrayBuffer());
  }

  const target = `${FileSystem.cacheDirectory}read-${Date.now()}-${sanitizeFileName(row.name)}`;
  const result = await FileSystem.downloadAsync(url, target);
  if (result.status !== 200) {
    throw new Error(`Could not read the file (HTTP ${result.status}).`);
  }
  const base64 = await FileSystem.readAsStringAsync(result.uri, {
    encoding: FileSystem.EncodingType.Base64,
  });
  await FileSystem.deleteAsync(target, { idempotent: true }).catch(() => {});
  return base64ToBytes(base64);
}

/**
 * Read a local URI into bytes.
 *
 * Web URIs are fetched directly (data: and blob: both work). On a device a
 * `file://` URI is read through expo-file-system — React Native's fetch cannot
 * reliably read the local filesystem, which is a classic silent breakage.
 */
export async function uriToBytes(uri: string): Promise<Uint8Array> {
  if (uri.startsWith("data:")) {
    return base64ToBytes(uri);
  }

  if (Platform.OS === "web") {
    const response = await fetch(uri);
    return new Uint8Array(await response.arrayBuffer());
  }

  const base64 = await FileSystem.readAsStringAsync(uri, {
    encoding: FileSystem.EncodingType.Base64,
  });
  return base64ToBytes(base64);
}

export interface StagedFile {
  /**
   * A URI the on-device tools can open. Native: a real file path. Web: a
   * base64 data URI (expo-image-manipulator only accepts local paths or data
   * URIs, and a blob URL is neither).
   */
  uri: string;
  bytes: Uint8Array;
  cleanup: () => Promise<void>;
}

/** Materialise a stored file for local editing (image/PDF tools). */
export async function stageVaultFile(row: VaultFileRow): Promise<StagedFile> {
  const url = viewUrlFor(row);

  if (Platform.OS === "web") {
    const bytes = await readVaultBytes(row);
    return {
      uri: `data:${row.mimeType};base64,${bytesToBase64(bytes)}`,
      bytes,
      cleanup: async () => {},
    };
  }

  const target = `${FileSystem.cacheDirectory}stage-${Date.now()}-${sanitizeFileName(row.name)}`;
  const result = await FileSystem.downloadAsync(url, target);
  if (result.status !== 200) {
    throw new Error(`Could not open the file (HTTP ${result.status}).`);
  }
  const base64 = await FileSystem.readAsStringAsync(result.uri, {
    encoding: FileSystem.EncodingType.Base64,
  });
  return {
    uri: result.uri,
    bytes: base64ToBytes(base64),
    cleanup: async () => {
      await FileSystem.deleteAsync(target, { idempotent: true }).catch(() => {});
    },
  };
}
